"""A new character starts with the author's settings, 2026-11-01.

Defaults.lua is generated by tools/export_defaults.py from the author's saved
settings. Core.lua copies it once, for a character with no saved settings, and
leaves out pixel positions that this screen cannot hold. Characters that already
have settings are untouched. Whether the layout looks right on a given screen
stays an in-game check.
"""
import unittest

from wowlua import LuaRuntime

from test_audit_2026_10_25 import source

PRELUDE = r'''
    CLASSIC_API_VERSION, SUPERWOW_VERSION = 11711, "2.2"
    function SetCVar() end
    function CreateFrame() return { RegisterEvent = function() end, SetScript = function() end } end
    SlashCmdList = {}
    function GetScreenWidth() return %d end
    function GetScreenHeight() return %d end
    %s
'''

DEFAULTS = r'''
    FostercareTweaks_Defaults = {
        ["Auto Stance"] = 1,
        ["Hide Gryphons"] = 1,
        overwrites = { minimap_scale = 1.35, uf_buff_size = 20 },
        unitframe_positions = {
            standard_player = { point = "TOPLEFT", relPoint = "TOPLEFT", x = 592, y = -618 },
            far_right = { point = "TOPLEFT", relPoint = "TOPLEFT", x = 1511, y = -100 },
            standard_target_buffs = { point = "TOPRIGHT", relPoint = "TOPRIGHT", x = 44, y = 45 },
        },
        actionbars = { enabled = true, bars = {
            extra = { visible = true, scale = 0.9, x = 447, y = 147 },
            left = { visible = true, x = 1631, y = 714 },
        } },
    }
'''


def load(width, height, saved=None):
    lua = LuaRuntime(unpack_returned_tuples=True)
    lua.execute(PRELUDE % (width, height, DEFAULTS))
    if saved is not None:
        lua.execute("FostercareTweaks_Config = " + saved)
    lua.execute(source("Core.lua") + "\nif FostercareTweaks then FostercareTweaks.ActionBars = { Initialize = function() end } end")
    return lua


class NewCharacter(unittest.TestCase):
    def test_switches_and_sizes_come_from_the_defaults(self):
        lua = load(1920, 1080)
        self.assertEqual(lua.eval('FostercareTweaks_Config["Auto Stance"]'), 1)
        self.assertEqual(lua.eval("FostercareTweaks_Config.overwrites.minimap_scale"), 1.35)
        self.assertEqual(lua.eval("FostercareTweaks_Config.actionbars.bars.extra.scale"), 0.9)

    def test_positions_that_fit_the_screen_are_kept(self):
        lua = load(1920, 1080)
        self.assertEqual(lua.eval("FostercareTweaks_Config.unitframe_positions.standard_player.x"), 592)
        self.assertEqual(lua.eval("FostercareTweaks_Config.unitframe_positions.far_right.x"), 1511)
        self.assertEqual(lua.eval("FostercareTweaks_Config.actionbars.bars.left.x"), 1631)

    def test_positions_outside_a_smaller_screen_are_left_out(self):
        lua = load(1024, 768)
        positions = lua.eval("FostercareTweaks_Config.unitframe_positions")
        self.assertIsNone(positions.far_right)                      # x 1511 does not fit 1024
        self.assertEqual(positions.standard_player.x, 592)          # this one does
        self.assertEqual(positions.standard_target_buffs.x, 44)     # relative to its frame: small offsets stay
        bars = lua.eval("FostercareTweaks_Config.actionbars.bars")
        self.assertIsNone(bars.left.x)                              # a bar that cannot be placed uses its default spot
        self.assertTrue(bars.left.visible)                          # but keeps its other settings
        self.assertEqual(bars.extra.x, 447)

    def test_the_defaults_table_is_copied_not_shared(self):
        lua = load(1920, 1080)
        lua.execute('FostercareTweaks_Config.overwrites.minimap_scale = 1')
        self.assertEqual(lua.eval("FostercareTweaks_Defaults.overwrites.minimap_scale"), 1.35)


class ExistingCharacter(unittest.TestCase):
    def test_saved_settings_are_never_replaced(self):
        lua = load(1920, 1080, '{ ["Auto Stance"] = 0, overwrites = { minimap_scale = 1 } }')
        self.assertEqual(lua.eval('FostercareTweaks_Config["Auto Stance"]'), 0)
        self.assertEqual(lua.eval("FostercareTweaks_Config.overwrites.minimap_scale"), 1)
        self.assertIsNone(lua.eval('FostercareTweaks_Config["Hide Gryphons"]'))
        self.assertIsNone(lua.eval("FostercareTweaks_Config.unitframe_positions"))


class TheShippedFile(unittest.TestCase):
    def test_no_chat_history_or_character_lists_are_shipped(self):
        text = source("Defaults.lua")
        for private in ("chathistory", "FostercareTweaks_Cache", "Hplayer", "Y'Shaarj"):
            self.assertNotIn(private, text)
        self.assertNotIn('["actions"]', text)
        self.assertNotIn("actions =", text)

    def test_it_loads_before_core(self):
        toc = source("FostercareTweaks.toc")
        self.assertLess(toc.index("Defaults.lua"), toc.index("Core.lua"))


if __name__ == "__main__":
    unittest.main()
